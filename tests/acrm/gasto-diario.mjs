import { JSDOM } from 'jsdom';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const dom = new JSDOM('<main></main>', { runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
const timers = new Map();
let serial = 0;
w.setInterval = (fn) => { timers.set(++serial, fn); return serial; };
w.clearInterval = (id) => timers.delete(id);
w.eval(readFileSync(new URL('../../src/modules/alertas-gasto/gasto-diario.js', import.meta.url), 'utf8'));
const api = w.LRGastoDiario;
const marcas = [
  { marca: 'Lima <Retail>', moneda: 'PEN', estado: { tono: 'rose', texto: 'Se pasará' }, presupuesto: 1200, consumido: .612, avanceMes: .3, proyeccion: 2446 },
  { marca: 'Amador', moneda: 'PEN', estado: { tono: 'green', texto: 'En ritmo' }, presupuesto: 2000, consumido: .25, avanceMes: .3, proyeccion: 1800 },
  { marca: 'Tierra', moneda: 'PEN', estado: { tono: 'amber', texto: 'Quedará corto' }, presupuesto: 3000, consumido: .1, avanceMes: .3, proyeccion: 1000 }
];
const rows = api.demoRows(marcas, '2026-11', '2026-11-09');
assert.equal(rows.length, 27);
const total = api.series(rows, '', '2026-11-03', '2026-11-05');
assert.equal(total.length, 3);
for (const day of total) {
  const sum = marcas.reduce((n, m) => n + api.series(rows, m.marca, day.fecha, day.fecha)[0].monto, 0);
  assert.equal(day.monto, sum, 'total equals sum of the brands on the same day');
}
assert.equal(api.variation(540, 480).percent, 12.5);
assert.equal(api.variation(0, 50).percent, -100);
assert.equal(api.variation(50, 0).percent, null);
assert.equal(api.variation(50, undefined).delta, null);
const counts = Object.fromEntries(marcas.map(m => [m.marca, 0]));
for (let i = 0; i < 1000; i++) counts[api.pick(marcas, '', () => i / 1000)]++;
assert.equal(counts['Lima <Retail>'], 600);
assert.equal(counts.Amador, 100);
assert.equal(counts.Tierra, 300);
assert.notEqual(api.pick(marcas, marcas[0].marca, () => 0), marcas[0].marca);
const root = w.document.querySelector('main');
const config = { mes: '2026-11', hasta: '2026-11-09', marcas };
api.mount(root, config);
const q = (s) => root.querySelector(s);
assert.equal(timers.size, 1);
assert.equal(q('retail'), null, 'brand names are escaped');
assert.match(root.textContent, /Datos de ejemplo/);
assert.equal(q('[data-gd-brand]').value, '');
q('[data-gd-view]').click();
assert.equal(q('[data-gd-brand]').value, marcas[0].marca);
assert.match(q('[data-gd-subtitle]').textContent, /Lima <Retail>/);
assert.equal(q('.gd-value').textContent, new Intl.NumberFormat('es-PE', {style:'currency',currency:'PEN',maximumFractionDigits:2}).format(rows[8].monto));
const change = (selector, value) => { q(selector).value = value; q(selector).dispatchEvent(new w.Event('change')); };
change('[data-gd-from]', '2026-11-05');
change('[data-gd-to]', '2026-11-05');
assert.equal(root.querySelectorAll('.gd-chart circle').length, 1, 'one-day range remains visible');
assert.match(q('.gd-kpi').textContent, /4 nov/, 'single-day range compares to the prior calendar day');
const before = q('[data-gd-body]').innerHTML;
change('[data-gd-from]', '2026-11-08');
assert.match(q('[data-gd-error]').textContent, /rango válido/);
assert.equal(q('[data-gd-body]').innerHTML, before, 'invalid range does not change the chart');
change('[data-gd-from]', '2026-11-01');
change('[data-gd-to]', '2026-11-01');
assert.match(q('.gd-kpi').textContent, /Sin base de comparación/);
q('[data-gd-next]').click();
const next = q('[data-gd-review] strong').textContent;
assert.notEqual(next, marcas[0].marca);
assert.equal(q('[data-gd-brand]').value, marcas[0].marca, 'rotation alone does not change the chosen filter');
q('[data-gd-prev]').click();
assert.equal(q('[data-gd-review] strong').textContent, marcas[0].marca);
q('[data-gd-pause]').click();
for (let i = 0; i < 10; i++) [...timers.values()].forEach(fn => fn());
assert.equal(q('[data-gd-review] strong').textContent, marcas[0].marca);
q('[data-gd-pause]').click();
for (let i = 0; i < 8; i++) [...timers.values()].forEach(fn => fn());
assert.equal(q('[data-gd-review] strong').textContent, next, 'automatic rotation resumes');
api.mount(root, config);
assert.equal(timers.size, 1, 'remount replaces the timer');
assert.equal(q('[data-gd-brand]').value, marcas[0].marca, 'filters survive a refresh');
api.mount(root, { ...config, mes: '2026-10', hasta: '2026-10-31' });
assert.equal(q('[data-gd-brand]').value, '');
assert.equal(q('[data-gd-to]').value, '2026-10-31');
api.mount(root, { ...config, marcas: [marcas[0]] });
assert.equal(q('[data-gd-next]').disabled, true);
api.unmount();
assert.equal(timers.size, 0, 'leaving the module releases timers');
api.mount(root, { ...config, marcas: [] });
assert.equal(root.hidden, true);
w.close();
console.log('PASS gasto diario: totals, date ranges, comparison, weighted rotation, filters, escaping, pause and cleanup');
